def generate_translations():
    with open('data/cis_items.json', 'r', encoding='utf-8') as f:
        cis_items = json.load(f)

    translations = {}

    for item in cis_items:
        code = item['code']
        description = item['description']

        # Translate description
        translated_desc = translate_cis_item(description)

        # Keep original code but update description
        translations[code] = {
            "code": code,
            "description": translated_desc,
            "level": item.get('level', ''),
            "full_text": f"{code} ({item.get('level', '')}) {translated_desc}"
        }

    with open('data/cis_items.zh_hk.json', 'w', encoding='utf-8') as f:
        json.dump(translations, f, ensure_ascii=False, indent=4)

    print(f"Generated translations for {len(translations)} items.")

if __name__ == "__main__":
    generate_translations()
